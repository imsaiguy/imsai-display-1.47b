# Renders anti-aliased glyph bitmaps (ASCII 32..126) from installed Windows fonts
# and writes them as C arrays to ..\main\fonts.h. No third-party libraries needed.
$ErrorActionPreference = "Stop"

Add-Type -ReferencedAssemblies System.Drawing -TypeDefinition @"
using System;
using System.Collections.Generic;
using System.Drawing;
using System.Drawing.Imaging;
using System.Drawing.Text;
using System.Text;

public static class FontGen
{
    public static string Generate(string family, float px, int style, string name)
    {
        FontStyle fs = (FontStyle)style;
        StringBuilder sb = new StringBuilder();
        using (Font font = new Font(family, px, fs, GraphicsUnit.Pixel))
        {
            FontFamily ff = font.FontFamily;
            float ascentPx = ff.GetCellAscent(fs) * px / ff.GetEmHeight(fs);
            float descentPx = ff.GetCellDescent(fs) * px / ff.GetEmHeight(fs);
            int pad = (int)Math.Ceiling(px * 0.5f);
            int cw = (int)Math.Ceiling(px * 2.0f) + 2 * pad;
            int ch = (int)Math.Ceiling(px * 1.8f) + 2 * pad;
            StringFormat sf = new StringFormat(StringFormat.GenericTypographic);
            sf.FormatFlags |= StringFormatFlags.MeasureTrailingSpaces | StringFormatFlags.NoWrap;

            List<byte> bitmap = new List<byte>();
            StringBuilder glyphs = new StringBuilder();

            for (int c = 32; c <= 126; c++)
            {
                string s = ((char)c).ToString();
                int w = 0, h = 0, xoff = 0, yoff = 0;
                float adv;
                int offset = bitmap.Count;
                using (Bitmap bmp = new Bitmap(cw, ch, PixelFormat.Format32bppArgb))
                using (Graphics g = Graphics.FromImage(bmp))
                {
                    g.Clear(Color.Black);
                    g.TextRenderingHint = TextRenderingHint.AntiAlias;
                    adv = g.MeasureString(s, font, new PointF(0, 0), sf).Width;
                    g.DrawString(s, font, Brushes.White, pad, pad, sf);

                    BitmapData bd = bmp.LockBits(new Rectangle(0, 0, cw, ch), ImageLockMode.ReadOnly, PixelFormat.Format32bppArgb);
                    byte[] raw = new byte[bd.Stride * ch];
                    System.Runtime.InteropServices.Marshal.Copy(bd.Scan0, raw, 0, raw.Length);
                    int stride = bd.Stride;
                    bmp.UnlockBits(bd);

                    int minx = cw, maxx = -1, miny = ch, maxy = -1;
                    for (int y = 0; y < ch; y++)
                        for (int x = 0; x < cw; x++)
                            if (raw[y * stride + x * 4 + 2] > 6)
                            {
                                if (x < minx) minx = x;
                                if (x > maxx) maxx = x;
                                if (y < miny) miny = y;
                                if (y > maxy) maxy = y;
                            }
                    if (maxx >= 0)
                    {
                        w = maxx - minx + 1;
                        h = maxy - miny + 1;
                        xoff = minx - pad;
                        yoff = (int)Math.Round(miny - pad - ascentPx);
                        for (int y = miny; y <= maxy; y++)
                            for (int x = minx; x <= maxx; x++)
                                bitmap.Add(raw[y * stride + x * 4 + 2]);
                    }
                }
                int adv16 = (int)Math.Round(adv * 16.0f);
                glyphs.AppendFormat("    {{{0}, {1}, {2}, {3}, {4}, {5}}}, /* '{6}' */\n", offset, w, h, xoff, yoff, adv16,
                    c == 92 ? "\\\\" : (c == 39 ? "\\'" : s));
            }

            sb.AppendFormat("/* {0} {1}px style {2} */\n", family, px, style);
            sb.AppendFormat("static const uint8_t {0}_bitmap[{1}] = {{\n", name, bitmap.Count);
            for (int i = 0; i < bitmap.Count; i++)
            {
                if (i % 24 == 0) sb.Append("    ");
                sb.Append(bitmap[i]).Append(',');
                sb.Append((i % 24 == 23) ? "\n" : " ");
            }
            sb.Append("\n};\n");
            sb.AppendFormat("static const glyph_t {0}_glyphs[] = {{\n{1}}};\n", name, glyphs.ToString());
            sb.AppendFormat("static const font_t {0} = {{ {0}_glyphs, {0}_bitmap, 32, 126, {1}, {2} }};\n\n",
                name, (int)Math.Round(ascentPx), (int)Math.Ceiling(ascentPx + descentPx));
        }
        return sb.ToString();
    }
}
"@

$out = New-Object System.Text.StringBuilder
[void]$out.Append("// Generated by tools/gen_fonts.ps1 from installed Windows fonts. Do not edit by hand.`n")
[void]$out.Append("#pragma once`n#include <stdint.h>`n`n")
[void]$out.Append("typedef struct { uint32_t off; uint8_t w, h; int8_t xoff, yoff; uint16_t adv16; } glyph_t;`n")
[void]$out.Append("typedef struct { const glyph_t *glyphs; const uint8_t *bitmap; int first, last; int ascent; int line_height; } font_t;`n`n")

# Title: calligraphic; subtitle: classic serif
[void]$out.Append([FontGen]::Generate("Monotype Corsiva", 46, 0, "font_title"))
[void]$out.Append([FontGen]::Generate("Palatino Linotype", 15, 0, "font_sub"))

$path = Join-Path $PSScriptRoot "..\main\fonts.h"
[System.IO.File]::WriteAllText($path, $out.ToString(), (New-Object System.Text.UTF8Encoding($false)))
"Wrote " + (Resolve-Path $path) + " (" + [math]::Round((Get-Item $path).Length / 1KB) + " KB of C source)"
