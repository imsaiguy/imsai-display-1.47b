"""Measures the front-panel LEDs of a real IMSAI 8080 in a screen recording and writes main/leds.h:
the LED positions on the 320x172 screen and a per-frame brightness table for all 44 LEDs.

    python tools/extract_leds.py [recording.mkv]        (needs: pip install --user imageio-ffmpeg numpy)

The LED sites in the photo come from tools/led_sites.csv (same order as the table below).
"""
import os, subprocess, sys
import numpy as np
import imageio_ffmpeg

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VIDEO = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "assets", "front_panel_leds.mkv")
W, H = 1210, 516          # frame size of the recording

# LED centres in the recording (x per LED, y of the row), read off the video frames.
# Order must match tools/led_sites.csv: out, stat, addH, data, addL, ctl
ROWS = [
    ("out",  78,  [73, 119, 169, 215, 262, 310, 356, 403]),     # PROGRAMMED OUTPUT 7..0
    ("stat", 157, [73, 119, 167, 214, 261, 309, 355, 401]),     # MEMR INP M1 OUT HLTA STACK WO INTA
    ("addH", 235, [73, 120, 167, 215, 262, 309, 355, 401]),     # ADDRESS BUS A15..A8
    ("data", 161, [496, 541, 587, 632, 678, 723, 769, 815]),    # DATA BUS D7..D0
    ("addL", 239, [494, 540, 586, 632, 678, 724, 768, 815]),    # ADDRESS BUS A7..A0
    ("ctl",  245, [998, 1044, 1088, 1131]),                     # INTE RUN WAIT HOLD
]
OFF_G, ON_G = 45.0, 190.0   # green-channel value of an LED that is off / fully on

raw = subprocess.run([imageio_ffmpeg.get_ffmpeg_exe(), "-hide_banner", "-loglevel", "error", "-i", VIDEO,
                      "-fps_mode", "passthrough", "-f", "rawvideo", "-pix_fmt", "rgb24", "-"],
                     capture_output=True, check=True).stdout
n = len(raw) // (W * H * 3)
G = np.frombuffer(raw, np.uint8)[: n * W * H * 3].reshape(n, H, W, 3)[:, :, :, 1].astype(np.float32)
Gmax = G.max(0)

series = {}
for name, y0, xs in ROWS:
    lst = []
    for x0 in xs:
        y1, y2, x1, x2 = y0 - 8, y0 + 9, x0 - 8, x0 + 9
        box = Gmax[y1:y2, x1:x2]
        wgt = np.clip(box - box.min(), 0, None) ** 2
        yy, xx = np.mgrid[y1:y2, x1:x2]
        cy = int(round((wgt * yy).sum() / wgt.sum()))
        cx = int(round((wgt * xx).sum() / wgt.sum()))
        lst.append(G[:, cy - 2:cy + 3, cx - 2:cx + 3].mean((1, 2)))
    series[name] = lst

# The PROGRAMMED OUTPUT row sits behind a bright reflection that fools the measurement on its left half.
# Its right-most LED (bit 0) is clean; bits 5,3,2,1,0 switch together, the others stay dark.
tmpl = series["out"][7]
for i in range(8):
    series["out"][i] = tmpl if i in (2, 4, 5, 6, 7) else np.full(n, 0.0, np.float32)

levels = np.zeros((n, 44), np.uint8)
col = 0
for name, _, xs in ROWS:
    for i in range(len(xs)):
        lv = np.clip((series[name][i] - OFF_G) / (ON_G - OFF_G), 0, 1)
        levels[:, col] = np.round(lv * 255)
        col += 1

# LED positions on the screen (the panel image is scaled 539x200 -> 320x119 and centred vertically in 172 rows)
sites = [l.strip().split(",") for l in open(os.path.join(ROOT, "tools", "led_sites.csv")) if l.strip() and not l.startswith("#")]
assert len(sites) == 44, len(sites)
sx, sy, oy = 320.0 / 539.0, 119.0 / 200.0, 26.0

out = ["// Generated by tools/extract_leds.py from assets/front_panel_leds.mkv. Do not edit by hand.",
       "#pragma once", "#include <stdint.h>", "",
       "#define LED_COUNT  44", "#define LED_FRAMES %d" % n, "#define LED_FPS    30", "",
       "// LED centres on the 320x172 screen (pixel-corner coordinates), order: out, stat, addH, data, addL, ctl",
       "static const float led_xy[LED_COUNT][2] = {"]
for s in sites:
    out.append("    {%.2ff, %.2ff}, /* %s%s */" % (float(s[2]) * sx, oy + float(s[3]) * sy, s[0], s[1]))
out += ["};", "", "// Brightness 0..255 of every LED in every frame of the recording (30 frames/s, loops)",
        "static const uint8_t led_anim[LED_FRAMES][LED_COUNT] = {"]
for f in range(n):
    out.append("    {" + ",".join(str(int(v)) for v in levels[f]) + "},")
out.append("};")
open(os.path.join(ROOT, "main", "leds.h"), "w", newline="\n").write("\n".join(out) + "\n")
print("wrote main/leds.h:", n, "frames x 44 LEDs")
for name, _, xs in ROWS:
    base = sum(len(r[2]) for r in ROWS[:[r[0] for r in ROWS].index(name)])
    print("%-5s" % name, " ".join("%3d" % int(levels[:, base + i].mean()) for i in range(len(xs))), " (mean level)")
